const rankOrder: AdultRank[] = ['III', 'II', 'I', 'КМС', 'МС'];

function parseTime(value: string): number {
  const parts = value.split(':').map(Number);
  return parts.length === 1 ? parts[0] : parts[0] * 60 + parts[1];
}

export function getRankStandards(stroke: string, distance: number, poolLength: number): RankStandard[] {
  const eventStandards = standards[`${stroke}|${distance}|${poolLength}`];
  if (!eventStandards) return [];

  return rankOrder.map((rank) => ({
    rank,
    timeSeconds: parseTime(eventStandards[rank]),
    color: rankColors[rank],
  }));
}
